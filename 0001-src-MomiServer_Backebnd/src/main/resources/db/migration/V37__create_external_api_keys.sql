CREATE TABLE t_external_api_keys (
    id UUID PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    key_prefix VARCHAR(16) NOT NULL,
    key_hash CHAR(64) NOT NULL UNIQUE,
    scopes TEXT[] NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'REVOKED')),
    expires_at TIMESTAMPTZ,
    last_used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(255) NOT NULL,
    revoked_at TIMESTAMPTZ,
    revoked_by VARCHAR(255),
    request_window TIMESTAMPTZ,
    request_count INTEGER NOT NULL DEFAULT 0 CHECK (request_count >= 0),
    CHECK (cardinality(scopes) > 0 AND scopes <@ ARRAY['inventory:read', 'inventory:write']::TEXT[])
);

CREATE TABLE t_external_api_key_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_key_id UUID NOT NULL REFERENCES t_external_api_keys(id),
    event_type VARCHAR(20) NOT NULL CHECK (event_type IN ('ISSUED', 'REVOKED')),
    actor VARCHAR(255) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE t_external_inventory_operations (
    api_key_id UUID NOT NULL REFERENCES t_external_api_keys(id),
    operation_id UUID NOT NULL,
    request_hash CHAR(64) NOT NULL,
    response JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (api_key_id, operation_id)
);

INSERT INTO m_api_versions(api_group, version, status)
VALUES ('external', 'v1', 'active')
ON CONFLICT (api_group, version) DO NOTHING;

COMMENT ON TABLE t_external_api_keys IS '外部連携単位のAPIキー。原文は保存せずSHA-256ハッシュのみ保持する。';
COMMENT ON TABLE t_external_api_key_events IS 'APIキー発行・無効化の監査履歴。';
COMMENT ON TABLE t_external_inventory_operations IS '外部APIキー単位の数量操作重複防止と初回応答。';
