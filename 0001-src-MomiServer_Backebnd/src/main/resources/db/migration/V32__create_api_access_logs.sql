CREATE TABLE t_api_access_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    occurred_at TIMESTAMPTZ NOT NULL,
    http_method VARCHAR(10) NOT NULL,
    request_path TEXT NOT NULL,
    endpoint_pattern VARCHAR(1024),
    status_code SMALLINT NOT NULL,
    duration_ms BIGINT NOT NULL,
    source_type VARCHAR(20) NOT NULL,
    principal VARCHAR(255),
    ip_address VARCHAR(45),
    user_agent VARCHAR(512),
    error_code VARCHAR(100),
    created_dt TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_t_api_access_logs_status_code
        CHECK (status_code BETWEEN 100 AND 599),
    CONSTRAINT chk_t_api_access_logs_duration
        CHECK (duration_ms >= 0),
    CONSTRAINT chk_t_api_access_logs_source_type
        CHECK (source_type IN ('web', 'agent', 'iot', 'gateway', 'anonymous'))
);

CREATE INDEX idx_t_api_access_logs_occurred
    ON t_api_access_logs(occurred_at DESC);
CREATE INDEX idx_t_api_access_logs_status_occurred
    ON t_api_access_logs(status_code, occurred_at DESC);
CREATE INDEX idx_t_api_access_logs_source_occurred
    ON t_api_access_logs(source_type, occurred_at DESC);
CREATE INDEX idx_t_api_access_logs_principal_occurred
    ON t_api_access_logs(principal, occurred_at DESC);

COMMENT ON TABLE t_api_access_logs IS 'HTTP APIへのアクセス履歴を機密情報を除外して記録する。';
COMMENT ON COLUMN t_api_access_logs.request_id IS 'サーバーがAPIリクエストごとに発行する外部参照用UUID。';
COMMENT ON COLUMN t_api_access_logs.request_path IS 'クエリ文字列を含まないリクエストパス。';
COMMENT ON COLUMN t_api_access_logs.endpoint_pattern IS 'Spring MVCが解決したパス変数展開前のエンドポイントパターン。';
COMMENT ON COLUMN t_api_access_logs.source_type IS 'web、agent、iot、gateway、anonymousのいずれか。';
